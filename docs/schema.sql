-- Settlement database schema (PostgreSQL).
--
-- Mirrors what Hibernate creates from the entities in src/main/java/.../model
-- (spring.jpa.hibernate.ddl-auto=update). The app builds and migrates these tables itself on
-- startup; this file is for reference, or to create an empty database by hand.

CREATE TABLE persons (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                   VARCHAR(255) NOT NULL,
    email                  VARCHAR(255) NOT NULL UNIQUE,
    phone_number           VARCHAR(255) UNIQUE,
    picture_url            VARCHAR(255),
    hide_phone             BOOLEAN      NOT NULL DEFAULT false,
    hide_email             BOOLEAN      NOT NULL DEFAULT false,
    notifications_enabled  BOOLEAN      NOT NULL DEFAULT true,
    active                 BOOLEAN      NOT NULL DEFAULT true   -- false = deactivated account
);

-- Friend list ("Circle"). One row per direction.
CREATE TABLE person_friends (
    person_id  BIGINT NOT NULL REFERENCES persons(id),
    friend_id  BIGINT NOT NULL REFERENCES persons(id),
    PRIMARY KEY (person_id, friend_id)
);

CREATE TABLE groups (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(255) NOT NULL,
    join_code   VARCHAR(12)  NOT NULL UNIQUE,
    owner_id    BIGINT REFERENCES persons(id),
    created_at  TIMESTAMP(6)
);

CREATE TABLE group_members (
    group_id   BIGINT NOT NULL REFERENCES groups(id),
    person_id  BIGINT NOT NULL REFERENCES persons(id),
    PRIMARY KEY (group_id, person_id)
);

CREATE TABLE debts (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    debtor_id    BIGINT           NOT NULL REFERENCES persons(id) ON DELETE CASCADE,  -- who owes
    creditor_id  BIGINT           NOT NULL REFERENCES persons(id) ON DELETE CASCADE,  -- who gets paid
    amount       DOUBLE PRECISION NOT NULL,
    status       VARCHAR(255)     NOT NULL,  -- UNCONFIRMED | PENDING | SETTLED | DECLINED | DELETED
    settled_at   TIMESTAMP(6),
    note         VARCHAR(255),
    group_id     BIGINT REFERENCES groups(id),  -- optional tag; settlement ignores it
    deleted_at   TIMESTAMP(6),                  -- soft delete
    deleted_by   VARCHAR(255)
);

CREATE TABLE notifications (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_email  VARCHAR(255) NOT NULL,  -- matches persons.email (no FK)
    type             VARCHAR(255) NOT NULL,  -- PROPOSED | ACCEPTED | DECLINED | REROUTED | DELETED | RESTORED
    message          VARCHAR(500) NOT NULL,
    related_debt_id  BIGINT,                 -- debts.id (no FK)
    is_read          BOOLEAN      NOT NULL,
    created_at       TIMESTAMP(6) NOT NULL
);
